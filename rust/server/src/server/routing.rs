use poem::endpoint::DynEndpoint;
use poem::post;
use poem::session::{CookieConfig, CookieSession};
use std::sync::Arc;

use adl::gen::protoapp::apis::ui::{ApiRequests, WebRequests};

use crate::server::handlers;
use crate::server::poem_adl_interop::{new_access_token_checker, PoemRoutes};
use crate::server::AppState;

pub fn build_routes(state: AppState) -> Box<dyn DynEndpoint<Output = poem::Response>> {
    let access_token_checker = new_access_token_checker(state.config.jwt_access_secret.clone());

    let routes = PoemRoutes::new();

    // Add the ADL implemented handlers. The registration is generated by
    // #[derive(HttpApi)] from the ApiRequests struct, so every endpoint
    // declared in the ADL is mounted, and none can be forgotten.
    let routes = routes.adl_api_at(&ApiRequests::new(), Arc::new(handlers::Handlers));

    // Add handlers that need custom cookie handling. These are the ADL
    // WebRequests endpoints, which take poem's CookieJar and so are wired by
    // hand rather than through the generated registration above.
    let routes = routes
        .at(
            WebRequests::def_login().path,
            post(handlers::login_with_cookies),
        )
        .at(
            WebRequests::def_refresh().path,
            post(handlers::refresh_with_cookies),
        )
        .at(
            WebRequests::def_logout().path,
            post(handlers::logout_with_cookies),
        );

    // Add system state and required middleware
    let routes = routes
        .data(state)
        .data(access_token_checker)
        .with(CookieSession::new(CookieConfig::default().secure(false)));

    Box::new(routes.into_dyn_endpoint())
}
